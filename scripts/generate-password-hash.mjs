#!/usr/bin/env node

/**
 * Generate Password Hash for Admin Authentication
 *
 * Usage: node scripts/generate-password-hash.mjs <password>
 *
 * This will output the hash that should be set as ADMIN_PASSWORD_HASH
 * in your environment variables.
 */

function hashPassword(password, secret) {
  // Simple HMAC-like hash
  let hash = 0;
  const combined = password + secret;
  for (let i = 0; i < combined.length; i++) {
    const char = combined.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash; // Convert to 32bit integer
  }
  // Convert to hex and add some entropy
  const baseHash = Math.abs(hash).toString(16);
  const entropy = Buffer.from(password + secret).toString('base64').slice(0, 20);
  return `v1:${baseHash}:${entropy}`;
}

